#!/usr/bin/env python3
"""Which eval cases does this change actually put at risk?

WHY THIS IS NOT A FILE-LIST INTERSECTION
----------------------------------------
The obvious design -- tag each case with the files it depends on, intersect with
`git diff --name-only` -- was measured against the real 2026-08-26 change that added
`ring_resonator_thermal_control.md`, and it selects 14 of 14 cases. It cannot do better:
every routing case depends on `domains/_routing.md`, and `_routing.md` is touched by every
profile addition. A selector that always says "re-run everything" is a rubber stamp, and
the manual eyeball it replaces was already free.

So the routing dependency is not intersected, it is COMPUTED. `routing_sim` replays Gate A
Step 0 rung 1 over each case's own prompt and compares the resulting load-set against the
one recorded when the suite was last graded. On the same 2026-08-26 change that selects
1 of 14 -- case 14, which is precisely the case that was added for it.

Three axes select a case, and every selection names which one fired:

  content    a path in the case's `depends_on.grounded_in` was changed
  routing    the case is `routing_sensitive` and its computed load-set drifted from the
             baseline -- a file started or stopped loading for that prompt
  row_set    the manifest's row SET changed and the case carries
             `depends_on.manifest_shape == "row_set"`. Cases 11 and 12 are the suite's only
             non-positive controls and they break when a row is ADDED, which no
             pre-existing file list can express (case 12's assertion 1 rests on a
             zero-literal-keyword premise across all base rows)

WHAT IT DOES NOT DO
-------------------
It never grades. Grading stays exactly as `evals.json`'s `run.method` describes it: one
subagent per case, adversarial, evidence citing file + section. This tool only chooses
which cases are worth handing to that process. A case it does not select is a case whose
declared dependency and computed routing both went untouched -- that is a claim about the
recorded dependency, not a guarantee, so `--conservative` is there for when you would
rather re-run everything.

Rungs 2-4 of the Step 0 ladder are judgment and are not simulated (see routing_sim's
docstring). Cases whose routing is prose-forced -- 8 A1 and 10 A3 are the recorded ones --
are therefore under-served by the routing axis and are carried by the content axis instead.

The routing axis compares load-sets computed in `routing_sim.fold()`'s NFKC space, and it
uses the FLAT scan rather than Gate A's two-level one, so it over-approximates -- the safe
direction for a selector. A change to the matching rule itself (case sensitivity, folding,
or the two-level scan) moves every computed load-set at once, so the baseline must be
regenerated in the same commit that re-grades under the new rule, never before it.

Usage
    python tools/eval-impact.py                     # vs the working tree's HEAD
    python tools/eval-impact.py --ref HEAD~3        # vs an arbitrary ref
    python tools/eval-impact.py --files domains/_routing.md ...
    python tools/eval-impact.py --conservative      # select every case, no reasoning
    python tools/eval-impact.py --update-baseline   # after a graded run, re-record

Stdlib only, read-only except for --update-baseline.
"""

import argparse
import hashlib
import io
import json
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

from routing_sim import MANIFEST_ROW, load_set, parse_manifest, strip_comments

ROUTING = "domains/_routing.md"

SKILL_ROOT = Path(__file__).resolve().parent.parent
BASELINE = SKILL_ROOT / "evals" / "routing-baseline.json"

BASELINE_NOTE = (
    "Computed load-sets for each eval case's prompt under Gate A Step 0 rung 1, as of the "
    "last graded run. Generated by tools/eval-impact.py --update-baseline; consumed by the "
    "same tool's routing axis. This is NOT a claim that these are the only files a case's "
    "verdict depends on (rungs 2-4 of the resolution ladder are judgment and are not "
    "simulated) -- it is the mechanically decidable part, recorded so a later change can be "
    "diffed against it. Refresh it in the same commit that records a re-grade, never before."
)


def prose_sha(routing_text):
    """Fingerprint of everything in `_routing.md` EXCEPT its manifest rows.

    `_routing.md` is the one dependency that must not be intersected: it is touched by every
    profile addition, so intersecting it selects every routing case -- the rubber stamp this
    tool exists to avoid. But only the MANIFEST ROWS are what `routing_sim` models; the
    clusters, the two disambiguation tables, the exception register and § Maintenance are
    prose that several cases' evidence cites directly (cases 6, 8, 12 and 13 all ground an
    assertion in a disambiguation table). So the file is split: manifest rows are judged by
    the computed routing axis, everything else by the content axis, and this hash is how the
    second half is compared without storing the whole file in the baseline.
    """
    # Drop WHOLE manifest lines. Substituting the regex match alone leaves each row's
    # trailing "Active triggers?" cell behind, so adding a row would move this hash and
    # every routing case would be selected by the content axis -- the exact rubber stamp
    # this split exists to prevent.
    body = "\n".join(ln for ln in strip_comments(routing_text).splitlines()
                     if not MANIFEST_ROW.match(ln))
    return hashlib.sha256(re.sub(r"\s+", " ", body).strip().encode("utf-8")).hexdigest()


def git(*args):
    """Run a git command from the repo root; return stdout, or None if git fails."""
    r = subprocess.run(["git", *args], cwd=str(SKILL_ROOT), capture_output=True,
                       text=True, encoding="utf-8")
    return r.stdout if r.returncode == 0 else None


def skill_prefix():
    """Path of the skill root relative to the git repo root, forward-slashed with a
    trailing slash. This skill lives INSIDE ~/.claude's repo, so git reports
    `skills/scientific-research-guide/domains/...` while every dependency in evals.json is
    skill-root-relative. Getting this wrong silently selects nothing."""
    top = git("rev-parse", "--show-toplevel")
    if not top:
        return ""
    rel = SKILL_ROOT.resolve().relative_to(Path(top.strip()).resolve()).as_posix()
    return f"{rel}/" if rel not in (".", "") else ""


def changed_paths(ref, explicit):
    """Skill-root-relative paths of the files this change touches."""
    if explicit is not None:      # an explicitly EMPTY list means "nothing changed"
        return sorted(set(explicit))
    pre = skill_prefix()
    if ref:
        out = git("diff", "--name-only", ref) or ""
        raw = out.splitlines()
    else:
        # Working tree vs HEAD, plus untracked files: a new sub-profile is untracked
        # until it is staged, and it is exactly the change most worth selecting on.
        raw = (git("diff", "--name-only", "HEAD") or "").splitlines()
        raw += (git("ls-files", "--others", "--exclude-standard") or "").splitlines()
    return sorted({p[len(pre):] for p in raw if p.startswith(pre)})


def routing_text_at(ref):
    """`domains/_routing.md` as of `ref`, or None."""
    return git("show", f"{ref}:{skill_prefix()}domains/_routing.md")


def current_state():
    rows = parse_manifest((SKILL_ROOT / "domains" / "_routing.md").read_text(encoding="utf-8"))
    with io.open(SKILL_ROOT / "evals" / "evals.json", encoding="utf-8") as fh:
        cases = json.load(fh)["evals"]
    return rows, cases


def build_baseline(rows, cases):
    return {
        "generated": date.today().isoformat(),
        "note": BASELINE_NOTE,
        "manifest_rows": sorted(rows),
        "routing_prose_sha256": prose_sha(
            (SKILL_ROOT / ROUTING).read_text(encoding="utf-8")),
        "cases": {str(c["id"]): load_set(rows, c["prompt"]) for c in cases},
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", help="git ref to compare against (default: HEAD + untracked)")
    ap.add_argument("--files", nargs="*", help="skill-root-relative paths, instead of git")
    ap.add_argument("--conservative", action="store_true",
                    help="select every case; use when the baseline is stale or untrusted")
    ap.add_argument("--update-baseline", action="store_true",
                    help="re-record evals/routing-baseline.json from the current tree")
    args = ap.parse_args()

    rows, cases = current_state()

    if args.update_baseline:
        with io.open(BASELINE, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(build_baseline(rows, cases), fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        print(f"baseline written: {BASELINE.relative_to(SKILL_ROOT).as_posix()} "
              f"({len(rows)} manifest rows, {len(cases)} cases)")
        return 0

    if args.conservative:
        print("--conservative: select all " + ", ".join(str(c["id"]) for c in cases))
        return 0

    changed = changed_paths(args.ref, args.files)

    # Anchor for the routing axis: the state the suite was last graded against. An explicit
    # --ref overrides it, which is how a historical change can be replayed after the fact.
    if args.ref and routing_text_at(args.ref):
        before_text = routing_text_at(args.ref)
        before_rows = parse_manifest(before_text)
        before_loads = {str(c["id"]): load_set(before_rows, c["prompt"]) for c in cases}
        before_prose = prose_sha(before_text)
        anchor = f"_routing.md at {args.ref}"
    elif BASELINE.exists():
        with io.open(BASELINE, encoding="utf-8") as fh:
            base = json.load(fh)
        before_rows = {r: None for r in base["manifest_rows"]}
        before_loads = base["cases"]
        before_prose = base.get("routing_prose_sha256")
        anchor = f"baseline recorded {base['generated']}"
    else:
        print(f"no baseline at {BASELINE} and no --ref given.\n"
              f"run:  python tools/eval-impact.py --update-baseline", file=sys.stderr)
        return 2

    now_loads = {str(c["id"]): load_set(rows, c["prompt"]) for c in cases}
    row_set_changed = set(before_rows) != set(rows)

    # Split _routing.md between the two axes (see prose_sha). If only manifest rows moved,
    # the computed routing axis has already ruled on it and the content axis must stay out.
    content_changed = list(changed)
    prose_moved = (ROUTING in changed and before_prose is not None
                   and before_prose != prose_sha((SKILL_ROOT / ROUTING).read_text(encoding="utf-8")))
    if ROUTING in changed and not prose_moved:
        content_changed.remove(ROUTING)

    print(f"changed files ({len(changed)}), skill-root-relative:")
    for p in changed:
        print(f"    {p}")
    print(f"routing anchor: {anchor}")
    if ROUTING in changed:
        print(f"_routing.md: manifest rows -> routing axis; "
              f"non-manifest prose {'CHANGED -> also content axis' if prose_moved else 'unchanged'}")
    if row_set_changed:
        added, removed = sorted(set(rows) - set(before_rows)), sorted(set(before_rows) - set(rows))
        print(f"manifest row set CHANGED  +{added}  -{removed}")
    print()

    selected, informational = {}, []
    for c in cases:
        cid = str(c["id"])
        dep = c.get("depends_on") or {}
        why = []

        hit = sorted(set(dep.get("grounded_in", [])) & set(content_changed))
        if hit:
            why.append("content: " + ", ".join(hit))

        drifted = set(before_loads.get(cid, {})) != set(now_loads[cid])
        if drifted:
            gained = sorted(set(now_loads[cid]) - set(before_loads.get(cid, {})))
            lost = sorted(set(before_loads.get(cid, {})) - set(now_loads[cid]))
            detail = f"routing: load-set drift +{gained} -{lost}"
            if dep.get("routing_sensitive"):
                why.append(detail)
            else:
                informational.append(f"  case {cid:>2}  {detail} (not routing_sensitive)")

        if row_set_changed and dep.get("manifest_shape") == "row_set":
            why.append("row_set: manifest rows changed and this case depends on the row set")

        if why:
            selected[cid] = why

    ids = sorted(selected, key=int)
    print(f"RE-RUN {len(ids)} of {len(cases)} cases: {', '.join(ids) if ids else '(none)'}")
    for cid in ids:
        print(f"  case {cid:>2}")
        for w in selected[cid]:
            print(f"       - {w}")
    if informational:
        print("\ninformational (routing moved but the case does not depend on routing):")
        print("\n".join(informational))
    if not ids:
        print("\nNo declared dependency was touched and no computed load-set moved.\n"
              "That is a claim about the recorded dependencies, not a proof. If this change\n"
              "altered SKILL.md's Step 0 ladder or a profile's standing triggers in a way the\n"
              "evidence strings do not name, re-run with --conservative.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
